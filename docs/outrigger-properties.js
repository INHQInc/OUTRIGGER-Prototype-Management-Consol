/* SynXis deep link. The site already builds these for every offer tile — it has
 * simply never put a date in one, which is very likely why tile "Book Now"
 * gained one click in eighteen days: it lands on an empty search form. */
window.outriggerBookingUrl = function (p, arrive, depart, opts) {
  var o = opts || {};
  var q = ['chain=18497', 'level=hotel', 'hotel=' + p.sabreId,
           'adult=' + (o.adults || 2), 'rooms=' + (o.rooms || 1)];
  if (arrive) q.push('arrive=' + arrive);   /* YYYY-MM-DD */
  if (depart) q.push('depart=' + depart);
  return 'https://reservation.outrigger.com/?' + q.join('&');
};

/* THE ANTIMERIDIAN. The estate runs Mauritius (57E) to Hawaii (-159). Raw
 * longitudes span 337 degrees, so fitBounds draws the long way round the globe.
 * Normalising negatives by +360 gives 147 degrees — the short way across the
 * Pacific, which is the map anyone actually wants. */
window.outriggerBounds = function (list) {
  var lo = 1e9, hi = -1e9, la = 1e9, lb = -1e9;
  list.forEach(function (p) {
    var x = p.lng < 0 ? p.lng + 360 : p.lng;
    lo = Math.min(lo, x); hi = Math.max(hi, x);
    la = Math.min(la, p.lat); lb = Math.max(lb, p.lat);
  });
  var w = function (x) { return x > 180 ? x - 360 : x; };
  return [[w(lo), la], [w(hi), lb]];
};

/* List-view columns are COMPUTED, not authored: anything every property in the
 * current scope shares tells the guest nothing, so it is suppressed. Switch
 * island and the columns change correctly on their own. */
window.outriggerDistinctive = function (list) {
  if (!list.length) return {};
  var sets = list.map(function (p) {
    return p.amenities.map(function (a) { return a.toLowerCase(); });
  });
  var common = sets[0].filter(function (a) {
    return sets.every(function (s) { return s.indexOf(a) > -1; });
  });
  var out = {};
  list.forEach(function (p) {
    out[p.sabreId] = p.amenities.filter(function (a) {
      return common.indexOf(a.toLowerCase()) === -1;
    });
  });
  return out;
};
